inline const FrameDef* find_frame(uint16_t id) {
  for (uint8_t i = 0; i < FRAME_COUNT; i++) {
    if (FRAMES[i].id == id) {
      return &FRAMES[i];
    }
  }
  return nullptr;
}

// CRC-8, MSB first, no reflection, start value 0 (0x0EC uses poly 0x1D and a final XOR of 0xBE).
inline uint8_t crc8(const uint8_t* d, uint8_t n, uint8_t poly) {
  uint8_t c = 0;
  for (uint8_t i = 0; i < n; i++) {
    c ^= d[i];
    for (uint8_t b = 0; b < 8; b++) {
      c = (c & 0x80) ? (uint8_t)((c << 1) ^ poly) : (uint8_t)(c << 1);
    }
  }
  return c;
}

// 0x500 is only sent while the ignition is on (starts about 15 s after ignition 1 in the car).
inline bool active_in_state(const FrameDef& d, uint8_t state) {
  if (d.kind == K_500) {
    return state >= BUS_ZUENDUNG1 && state <= BUS_AUS;
  }
  return true;
}

inline const char* state_name(uint8_t state) {
  static const char* const NAMES[BUS_STATE_COUNT] = {"closed", "awake", "ignition 1", "ignition 3",
                                                     "GO",     "driving", "ignition off"};
  return state < BUS_STATE_COUNT ? NAMES[state] : "?";
}

// Fills out[0..dlc-1] with frame number seq (0, 1, 2, ...) of the frame d in the state. age_min: vehicle age for
// 0x436 (24 bit), km: kilometres for 0x426 (16 bit, wraps at 65536 like in the car).
inline void build_frame(const FrameDef& d, uint8_t state, uint32_t seq, uint32_t age_min, uint32_t km, uint8_t out[8]) {
  if (state >= BUS_STATE_COUNT) {
    state = BUS_WACH;
  }
  const uint8_t variant = (d.kind == K_423) ? (uint8_t)((seq / 5) % 2) : 0;  // 0x423: 5 frames per variant (500 ms)
  for (uint8_t i = 0; i < 8; i++) {
    out[i] = d.data[state][variant][i];
  }
  switch (d.kind) {
    case K_19F:
      out[3] = (uint8_t)((out[3] & 0xF0) | ((5U * seq) & 0x0F));
      break;
    case K_157:
      out[1] = (uint8_t)((out[1] & 0x0F) | (((5U * seq) & 0x0F) << 4));
      break;
    case K_0EC:
      out[1] = (uint8_t)((out[1] & 0x0F) | ((seq & 0x0F) << 4));
      out[2] = (uint8_t)(crc8(out, 2, 0x1D) ^ 0xBE);
      break;
    case K_511: {
      static const uint8_t START[6] = {0x3A, 0x15, 0xC1, 0xF9, 0x53, 0x97};
      static const uint8_t STEP[6] = {63, 201, 185, 107, 13, 227};
      for (uint8_t i = 0; i < 6; i++) {
        out[1 + i] = (uint8_t)(START[i] + STEP[i] * seq);
      }
      break;
    }
    case K_426:
      out[4] = (uint8_t)((km >> 8) & 0xFF);
      out[5] = (uint8_t)(km & 0xFF);
      break;
    case K_436:
      out[0] = (state >= BUS_ZUENDUNG1 && state <= BUS_FAHRT) ? 0xAD : 0x80;
      out[1] = (uint8_t)((age_min >> 16) & 0xFF);
      out[2] = (uint8_t)((age_min >> 8) & 0xFF);
      out[3] = (uint8_t)(age_min & 0xFF);
      out[4] = 0x00;
      out[5] = 0x00;
      break;
    default:
      break;
  }
}

