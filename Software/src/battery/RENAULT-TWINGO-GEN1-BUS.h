inline const uint8_t* laden_end_table(uint16_t id) {
  switch (id) {
    case 0x419:
      return &LADEN_END_419[0][0];
    case 0x428:
      return &LADEN_END_428[0][0];
    case 0x42F:
      return &LADEN_END_42F[0][0];
    case 0x435:
      return &LADEN_END_435[0][0];
    case 0x4F7:
      return &LADEN_END_4F7[0][0];
    default:
      return nullptr;
  }
}

// Overwrites the bytes of the frame `out` (already built for its state) with the end form of the car, t_ms = time since the
// start of the end. Returns true when it changed something.
inline bool laden_end_form(uint16_t id, uint32_t t_ms, uint8_t dlc, uint8_t out[8]) {
  const uint8_t* table = laden_end_table(id);
  if (table != nullptr) {
    const uint32_t slot = t_ms / 100;
    if (slot >= LADEN_END_FRAMES) {
      return false;
    }
    for (uint8_t i = 0; i < 8 && i < dlc; i++) {
      out[i] = table[slot * 8 + i];
    }
    return true;
  }
  switch (id) {
    case 0x1C7:  // B3/B4: 04/34 for 0.42 s, 02/34 until 0.99 s, 02/36 until 2.03 s, 08/00 until 3.01 s, then 08/FE (awake)
      if (t_ms < 420) {
        out[3] = 0x04;
        out[4] = 0x34;
      } else if (t_ms < 990) {
        out[3] = 0x02;
        out[4] = 0x34;
      } else if (t_ms < 2030) {
        out[3] = 0x02;
        out[4] = 0x36;
      } else if (t_ms < 3010) {
        out[3] = 0x08;
        out[4] = 0x00;
      } else {
        out[3] = 0x08;
        out[4] = 0xFE;
      }
      return true;
    case 0x157:  // 3.02 s to 3.35 s: B6/B7 = 01/00 (33 frames), otherwise 00/80
      if (t_ms >= 3020 && t_ms < 3350) {
        out[6] = 0x01;
        out[7] = 0x00;
        return true;
      }
      return false;
    default:
      return false;
  }
}

// 0x423 at the end of the charge: byte 5 is 80 for the first 0.73 s (then A0 of the state "awake"), byte 0 is 87 from 0.33 s to
// 5.83 s (5.5 s). Byte 3 is FD in the state "awake" already.
inline bool laden_end_423(uint32_t t_ms, uint8_t out[8]) {
  bool changed = false;
  if (t_ms < 730) {
    out[5] = 0x80;
    changed = true;
  }
  if (laden_end_423_87(t_ms)) {
    out[0] = 0x87;
    changed = true;
  }
  return changed;
}

// 0x423 byte 3 and byte 5 while the bus wakes through the plug (regular frames k after the two wake frames, log 247.70 s on):
// frames 0 to 25: FD / 80, frames 26 to 79: FE / 80, frames 80 to 84: FE / 20 (byte 0 = 87 and byte 1 as in laden_wake_423()),
// then the state "charging" (FE / 20) gives them itself.
inline bool laden_wake_423_b3b5(uint32_t k, uint8_t& b3, uint8_t& b5) {
  if (k > LADEN_423_LAST) {
    return false;
  }
  b3 = (k < 26) ? 0xFD : 0xFE;
  b5 = (k < 80) ? 0x80 : 0x20;
  return true;
}

