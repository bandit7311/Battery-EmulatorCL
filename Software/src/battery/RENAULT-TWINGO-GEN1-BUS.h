inline const FrameDef* find_frame(uint16_t id) {
  for (uint8_t i = 0; i < FRAME_COUNT; i++) {
    if (FRAMES[i].id == id) {
      return &FRAMES[i];
    }
  }
  return nullptr;
}

// CRC-8, MSB first, no reflection, start value 0 (0x0EC uses poly 0x1D and a final XOR of 0xBE).
inline uint8_t crc8(const uint8_t* d, uint8_t n, uint8_t poly) {
  uint8_t c = 0;
  for (uint8_t i = 0; i < n; i++) {
    c ^= d[i];
    for (uint8_t b = 0; b < 8; b++) {
      c = (c & 0x80) ? (uint8_t)((c << 1) ^ poly) : (uint8_t)(c << 1);
    }
  }
  return c;
}

// 0x19F byte 5: CRC-8 (polynomial 0x2F, start 0, no final XOR) over the 12-bit value B2:B3hi as two bytes
// (V >> 8, V & 0xFF with V = B2 << 4 | high nibble of B3). Checked against every pair of the car log 22aaf176.
inline uint8_t crc19f(uint8_t b2, uint8_t b3_high_nibble) {
  const uint16_t v = (uint16_t)(((uint16_t)b2 << 4) | (b3_high_nibble & 0x0F));
  const uint8_t d[2] = {(uint8_t)(v >> 8), (uint8_t)(v & 0xFF)};
  return crc8(d, 2, 0x2F);
}

// 0x500 is only sent while the ignition is on (starts about 15 s after ignition 1 in the car).
inline bool active_in_state(const FrameDef& d, uint8_t state) {
  if (d.kind == K_500) {
    return state >= BUS_ZUENDUNG1 && state <= BUS_AUS;
  }
  return true;
}

inline const char* state_name(uint8_t state) {
  static const char* const NAMES[BUS_STATE_COUNT] = {"closed", "awake",   "ignition 1",   "ignition 3",
                                                     "GO",     "driving", "ignition off", "charging"};
  return state < BUS_STATE_COUNT ? NAMES[state] : "?";
}

// Byte 0 of 0x0EC while driving: after entering the state "driving" it walks a ramp and settles at 29 (first drive of
// the car log 22aaf176, T+216.4 s ...: 25 x90, 27 x13, 26 x4, 2A x6, 22 x1, 21 x328, 2B x3, 29 x212, 28 x26, then 29;
// one frame = 10 ms). The second drive of the log (T+1373 s) walks a different ramp (27 x821 ...); this one is replayed.
// n = frames since the state was entered.
inline uint8_t ec_drive_b0(uint32_t n) {
  struct Step {
    uint8_t b0;
    uint16_t frames;
  };
  static constexpr Step RAMP[9] = {{0x25, 90},  {0x27, 13}, {0x26, 4},   {0x2A, 6}, {0x22, 1},
                                   {0x21, 328}, {0x2B, 3},  {0x29, 212}, {0x28, 26}};
  for (const Step& st : RAMP) {
    if (n < st.frames) {
      return st.b0;
    }
    n -= st.frames;
  }
  return 0x29;
}

// Closing form of the last second before the bus goes silent (car log 22aaf176, session 2): 0x0ED carries 60 FF 00
// instead of 60 FF 80. Applied after build_frame() in the state "closed" while the bus shuts down.
inline void apply_closing_form(const FrameDef& d, uint8_t out[8]) {
  if (d.kind == K_0ED) {
    out[2] = 0x00;
  }
}

// Fills out[0..dlc-1] with frame number seq (0, 1, 2, ...) of the frame d in the state. age_min: vehicle age for
// 0x436 (24 bit), km: kilometres for 0x426 (24 bit in bytes 3-5). state_seq: frames since the state was entered (only
// 0x0EC while driving uses it).
// o426: -1 = none, otherwise (B1 << 8) | B2 for 0x426 (the transitional values of the car that are no state of their
// own). b7: byte 7 of 0x426 (the car sends 40 all the time).
inline void build_frame(const FrameDef& d, uint8_t state, uint32_t seq, uint32_t age_min, uint32_t km, uint8_t out[8],
                        uint32_t state_seq = 0, int32_t o426 = -1, uint8_t b7 = 0x40, int16_t b0_436 = -1) {
  if (state >= BUS_STATE_COUNT) {
    state = BUS_WACH;
  }
  const uint8_t variant = (d.kind == K_423) ? (uint8_t)((seq / 5) % 2) : 0;  // 0x423: 5 frames per variant (500 ms)
  for (uint8_t i = 0; i < 8; i++) {
    out[i] = d.data[state][variant][i];
  }
  switch (d.kind) {
    case K_19F:
      if (seq < WAKE_19F_FRAMES_A) {
        out[0] = out[1] = out[2] = 0xFF;
        out[3] = 0xF0;
        out[6] = 0x00;
      } else if (seq < WAKE_19F_FRAMES) {
        const uint8_t* r = WAKE_19F_RAMP[seq - WAKE_19F_FRAMES_A];
        out[0] = out[1] = 0x00;
        out[2] = r[0];
        out[3] = (uint8_t)(r[1] << 4);
        out[6] = 0x90;
      } else if (state == BUS_ZUENDUNG1 && state_seq < Z1_19F_RAMP_DONE) {
        if (state_seq >= Z1_19F_B6_FRAME) {
          out[6] = 0x50;
        }
        if (state_seq >= Z1_19F_RAMP_START) {
          out[0] = out[1] = Z1_19F_RAMP[state_seq - Z1_19F_RAMP_START];
        }
      } else if (state == BUS_ZUENDUNG1) {
        out[0] = out[1] = 0xA0;
        out[6] = 0x50;
      }
      out[3] = (uint8_t)((out[3] & 0xF0) | ((0x0FU + 5U * seq) & 0x0F));
      out[5] = crc19f(out[2], (uint8_t)(out[3] >> 4));
      break;
    case K_157:
      out[1] = (uint8_t)((out[1] & 0x0F) | (((5U * seq) & 0x0F) << 4));
      break;
    case K_0EC:
      if (state == BUS_FAHRT) {
        out[0] = ec_drive_b0(state_seq);
      }
      if (seq < WAKE_0EC_FRAMES) {
        out[0] = 0x10;  // wake-up form: the first 6 frames of every session in the car log (10 01 17 ... 10 51 C9)
      }
      out[1] = (uint8_t)((out[1] & 0x0F) | ((seq & 0x0F) << 4));
      out[2] = (uint8_t)(crc8(out, 2, 0x1D) ^ 0xBE);
      break;
    case K_0ED:
      if (seq < WAKE_0ED_FRAMES_A) {
        out[0] = 0xA3;  // wake-up form in the car log: 10 x A3 FF 00, then 21 x A3 FF 80, then the state value
        out[1] = 0xFF;
        out[2] = 0x00;
      } else if (seq < WAKE_0ED_FRAMES_A + WAKE_0ED_FRAMES_B) {
        out[0] = 0xA3;
        out[1] = 0xFF;
        out[2] = 0x80;
      }
      break;
    case K_511: {
      static const uint8_t START[6] = {0x3A, 0x15, 0xC1, 0xF9, 0x53, 0x97};
      static const uint8_t STEP[6] = {63, 201, 185, 107, 13, 227};
      for (uint8_t i = 0; i < 6; i++) {
        out[1 + i] = (uint8_t)(START[i] + STEP[i] * seq);
      }
      break;
    }
    case K_426:
      // Kilometres: 24 bit in bytes 3-5 (the car log shows 01 6A 70 = 92,784 km; the pack shows it as $925F). Byte 6 stays
      // 00 (fraction). Corrected 10.10.: before it was 16 bit in bytes 4-5 with byte 3 fixed at 01, which gave 72,380 km.
      out[3] = (uint8_t)((km >> 16) & 0xFF);
      out[4] = (uint8_t)((km >> 8) & 0xFF);
      out[5] = (uint8_t)(km & 0xFF);
      out[7] = (state == BUS_LADEN) ? 0x80 : b7;  // the car sends 80 all the time while it charges
      if (o426 >= 0) {
        out[1] = (uint8_t)((o426 >> 8) & 0xFF);
        out[2] = (uint8_t)(o426 & 0xFF);
        if ((o426 & O426_B7_80) != 0) {
          out[7] = 0x80;
        }
      }
      break;
    case K_436:
      out[0] = ((state >= BUS_ZUENDUNG1 && state <= BUS_FAHRT) || state == BUS_LADEN) ? 0xAD : 0x80;
      out[1] = (uint8_t)((age_min >> 16) & 0xFF);
      out[2] = (uint8_t)((age_min >> 8) & 0xFF);
      out[3] = (uint8_t)(age_min & 0xFF);
      out[4] = 0x00;
      out[5] = 0x00;
      if (b0_436 >= 0) {
        out[0] = (uint8_t)b0_436;  // the ramp of B0 while the bus wakes up through the plug / ends charging
      }
      break;
    default:
      break;
  }
}

