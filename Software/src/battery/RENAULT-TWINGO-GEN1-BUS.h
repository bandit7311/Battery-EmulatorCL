// Cell voltage broadcast (Prio 2, 10.10.): 19 frames with 5 cells + 0x5DD with one cell, about every 3 s. Layout
// (BMS_A10 = 0x5F7, confirmed by bench frames, e.g. 87 28 74 87 48 74 87 4F = 4162 4164 4164 4164 4164 mV):
//   Z1 = (B0 << 4) | (B1 >> 4)       Z2 = ((B1 & 0F) << 8) | B2     Z3 = (B3 << 4) | (B4 >> 4)
//   Z4 = ((B4 & 0F) << 8) | B5       Z5 = (B6 << 4) | (B7 >> 4)     mV = value + 2000
// Cell order = order of the frames below (A10 = cells 1-5 ... A28 = 91-95, 0x5DD = cell 96). 0x5EC stands in for A18
// (0x5D7 in the Zoe code, cells 41-45) - an assumption by exclusion, not measured.
// At wake-up the frames carry placeholders (FF FF ... or 00 ... 0F); they decode to 6095 resp. 2000 mV and fall out
// of the plausibility window.
inline constexpr uint8_t CELL_FRAME_COUNT = 20;
inline constexpr uint16_t CELL_FRAME_IDS[CELL_FRAME_COUNT] = {0x5F7, 0x5F4, 0x5F2, 0x5F1, 0x5F0, 0x5ED, 0x5EA,
                                                              0x5D9, 0x5EC, 0x5D6, 0x5CC, 0x5CB, 0x5C9, 0x5B7,
                                                              0x5B5, 0x5B4, 0x5AC, 0x5AD, 0x5A1, 0x5DD};
inline constexpr uint16_t CELL_MV_MIN = 2500;  // plausible window of a real cell
inline constexpr uint16_t CELL_MV_MAX = 4500;

// Index of an ID in CELL_FRAME_IDS, -1 if it is no cell frame.
inline int cell_frame_index(uint16_t id) {
  for (uint8_t i = 0; i < CELL_FRAME_COUNT; i++) {
    if (CELL_FRAME_IDS[i] == id) {
      return i;
    }
  }
  return -1;
}

// Decodes the cells of frame number idx (0..19) from the 8 data bytes: out_mV[k] = voltage of cell
// first_cell(idx) + k, 0 for a placeholder (outside the plausible window). Returns the number of cells in the frame
// (5, or 1 for 0x5DD).
inline uint8_t decode_cell_frame(uint8_t idx, const uint8_t d[8], uint16_t out_mV[5]) {
  const uint16_t raw[5] = {(uint16_t)((d[0] << 4) | (d[1] >> 4)), (uint16_t)(((d[1] & 0x0F) << 8) | d[2]),
                           (uint16_t)((d[3] << 4) | (d[4] >> 4)), (uint16_t)(((d[4] & 0x0F) << 8) | d[5]),
                           (uint16_t)((d[6] << 4) | (d[7] >> 4))};
  const uint8_t n = (idx == CELL_FRAME_COUNT - 1) ? 1 : 5;
  for (uint8_t k = 0; k < 5; k++) {
    const uint16_t mv = (uint16_t)(raw[k] + 2000);
    out_mV[k] = (k < n && mv >= CELL_MV_MIN && mv <= CELL_MV_MAX) ? mv : 0;
  }
  return n;
}

// Zero-based number of the first cell of frame idx.
inline uint8_t first_cell(uint8_t idx) {
  return (uint8_t)(idx * 5);
}

